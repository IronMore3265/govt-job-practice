FOOT = "BANGLA LITERATURE - THE NOTE"
AR = '<svg width="14" height="11" viewBox="0 0 17 13" fill="none" stroke="#1C1A16" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round"><path d="M1 6.5h14M10 1.5l5 5-5 5"/></svg>'
BN = "০১২৩৪৫৬৭৮৯"


def chain(steps, hl=(), lead=False):
    out = ['<div class="chain">']
    for i, s in enumerate(steps):
        if i or lead:
            out.append(f'<div class="ar">{AR}</div>')
        cls = "st hl" if i in hl else "st"
        if isinstance(s, tuple):
            out.append(f'<div class="{cls}">{s[0]}<small>{s[1]}</small></div>')
        else:
            out.append(f'<div class="{cls}">{s}</div>')
    out.append("</div>")
    return "".join(out)


def ledger(items):
    rows = "".join(f'<div class="li"><span class="n">{BN[i + 1]}</span><span class="nm">{t}</span></div>' for i, t in enumerate(items))
    return f'<div class="ledger">{rows}</div>'


def table(head, rows, widths):
    cols = "".join(f'<col style="width:{w}px">' for w in widths)
    th = "".join(f"<th>{h}</th>" for h in head)
    body = ""
    for r in rows:
        tds = ""
        for j, c in enumerate(r):
            tds += f'<td class="strong">{c}</td>' if j == 0 else f"<td>{c}</td>"
        body += f"<tr>{tds}</tr>"
    return f'<table class="grid"><colgroup>{cols}</colgroup><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>'


def card(title, inner, accent=False, label=None):
    lab = f'<span class="label">{label}</span>' if label else ""
    return f'<div class="card{" accent" if accent else ""}">{lab}<h4>{title}</h4>{inner}</div>'


PN = [0]


def page(num, title, tagline, body, foot, pn=None, first=True):
    PN[0] += 1
    pn = PN[0]
    head = ""
    if first:
        head = f'<h1 class="pt"><span class="n">{num}</span><span>{title}</span></h1><div class="tagline">{tagline}</div>'
    return f'<section class="page">{head}{body}<div class="footer"><span>{foot}</span><span class="pn">{pn}</span></div></section>'


def doc(title, pages):
    return f'<!doctype html><html lang="bn"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>{title}</title><link rel="stylesheet" href="HREF"></head><body>{"".join(pages)}</body></html>'


